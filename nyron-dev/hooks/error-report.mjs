/**
 * error-report.mjs — запись машинного события об ошибке в будку (STOVP-41).
 *
 * Разбор процесса до сих пор питался только жалобами людей: упавший хук или
 * сломавшийся скилл никто не фиксировал — человек либо не замечал, либо
 * молчал. Теперь падение оставляет строку в той же шине будки, что и обычные
 * сообщения агентов, но с kind='error': время, машина (hostname), источник
 * (имя хука/скилла) и текст ошибки.
 *
 *   node error-report.mjs <источник> <текст…>
 *
 * Зовут не руками, а через error-report.sh (он ищет node) — обычно из
 * guard.sh, который оборачивает хуки и скриптовые шаги скиллов.
 *
 * Молчание — единственное допустимое поведение при любой осечке: будки в
 * проекте нет, база занята, Node старый, каталог только на чтение — выходим 0
 * и ничего не печатаем. Сенсор не имеет права уронить или испачкать сессию.
 */
import fs from 'node:fs';
import { resolveHubDir } from '../hub/hub-dir.mjs';

const MAX_TEXT = 2000;

const source = (process.argv[2] || 'unknown').slice(0, 200);
const text = (process.argv.slice(3).join(' ') || '(без текста)').trim().slice(0, MAX_TEXT);

try {
  const hubDir = resolveHubDir();
  // Будку НЕ создаём: нет каталога — значит в этом проекте будки нет
  // (плагин стоит глобально, хуки срабатывают и в чужих репо, засорять их
  // каталогом .nyron-hub из-за одной ошибки нельзя).
  if (fs.existsSync(hubDir)) {
    const { HubDb } = await import('../hub/hub-db.mjs');
    new HubDb(hubDir).post({ from: source, text, kind: 'error' });
  }
} catch {
  // будка недоступна — молчим
}
process.exit(0);
