#!/usr/bin/env bash
# watch-nanny.sh — нянька вотчеров: обходит агентов, писавших в будку
# недавно, и поднимает связь тем, у кого вотчер не взведён.
#
# Зачем отдельно от Stop-хука: хук — профилактика (взводит сразу после
# хода), нянька — страховка. Она ловит случаи, где хука нет или он не
# сработал: сессия упала посреди хода, машина упёрлась в лимит, вотчер
# убит вместе с терминалом. Замер 12.08: у семи из четырнадцати активных
# агентов вотчера не было — без няньки они спят молча.
#
#   watch-nanny.sh [корень-проекта] [окно-минут] [порог-молчания-минут]
#
# ВАЖНО про критерий (ошибка первого прогона 12.08, исправлено): отсутствие
# вотчера НЕ значит «сессия спит». Вотчер одноразовый: сработал на событие,
# завершился, разбудил сессию — пока она обрабатывает ход, вотчера нет, и
# это нормальная фаза. Признак беды = вотчера нет И агент молчит дольше
# порога. Иначе нянька пишет работающим (в первом прогоне так и вышло:
# 11 писем, половина — тем, кто отвечал минуту назад).
#
# Что делает с найденным «спящим»: сначала пробует взвести вотчер сам
# (hub-rearm.sh) — это дёшево и не будит модель. Если у агента нет живой
# сессии, вотчер просто не за кем ходить: тогда пишет адресный пост в
# будку, чтобы сессия увидела просьбу при следующем чтении.
set -uo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="${1:-$PWD}"
WINDOW="${2:-45}"                 # кого считаем активным, минут
QUIET="${3:-12}"                  # молчит дольше этого — считаем спящим
MAX_PINGS="${MAX_PINGS:-2}"       # писем за прогон: лавина событий будит чужие вотчеры
HUB="$ROOT/.nyron-hub"
[ -d "$HUB" ] || { echo "нянька: нет будки в $ROOT" >&2; exit 1; }

MARK="$HUB/.watchers/.nanny"      # метки, чтобы не пинговать одного чаще раза в 15 минут
mkdir -p "$MARK"

# Активные агенты берём из самой будки: кто писал — тот работает.
# Служебные отправители (сторож, реаниматор, человек) вотчера не имеют.
# Берём агента вместе с тем, сколько минут он молчит: пинг положен только
# молчащим, взвод вотчера — всем без разбора (он дешёвый и модель не будит).
AGENTS="$(sqlite3 "$HUB/hub.db" "
  SELECT sender || ':' || CAST((julianday('now')-julianday(MAX(ts)))*1440 AS INT)
    FROM messages
   WHERE ts > datetime('now','-$WINDOW minutes')
     AND sender IS NOT NULL
     AND sender NOT IN ('watchdog','reanimator','errors','all','nanny')
     AND sender NOT LIKE '%@morda'
     AND sender NOT LIKE 'skill:%'
   GROUP BY sender" 2>/dev/null)"

rearmed=0; pinged=0; alive=0
for rec in $AGENTS; do
  a="${rec%:*}"; quiet_min="${rec##*:}"
  [ -n "$a" ] || continue
  if (cd "$ROOT" && "$HERE/hub-watch.sh" alive "$a" >/dev/null 2>&1); then
    alive=$((alive+1)); continue
  fi

  "$HERE/hub-rearm.sh" agent "$a" "$ROOT" >/dev/null 2>&1
  if (cd "$ROOT" && "$HERE/hub-watch.sh" alive "$a" >/dev/null 2>&1); then
    rearmed=$((rearmed+1)); continue
  fi

  # Взвести не удалось — сессия глухая. Пост в будку ей бесполезен: она не
  # проснётся, чтобы его прочитать (CTO 12.08). Поэтому сначала пробуем
  # РЕАЛЬНО разбудить через пульт (он умеет клавиши в панель tmux и
  # адресную доставку), и только если пульта нет — оставляем след в будке,
  # чтобы человек увидел, кто выпал.
  if curl -s -m 3 -o /dev/null -w '' -X POST 'http://127.0.0.1:4747/api/say' \
       -H 'content-type: application/json' -H 'x-morda: 1' \
       -d "{\"project\":\"nyron\",\"key\":\"$a\",\"text\":\"Вотчер будки не взведён — взведи hub-watch.sh watch $a фоном, иначе не проснёшься.\"}" 2>/dev/null; then
    :
  fi
  # Пишем ТОЛЬКО молчащим и не больше пары за прогон:
  # каждый пост — событие в шине, будящее чужие вотчеры.
  [ "$quiet_min" -ge "$QUIET" ] || continue
  [ "$pinged" -lt "$MAX_PINGS" ] || continue
  m="$MARK/$a"
  if [ -f "$m" ] && [ "$(( $(date +%s) - $(stat -f %m "$m" 2>/dev/null || echo 0) ))" -lt 900 ]; then
    continue
  fi
  touch "$m"
  node -e "
    const { HubDb } = await import('$HERE/hub-db.mjs');
    const hub = new HubDb('$HUB');
    hub.post({ from: 'nanny', to: '$a',
      text: '[нянька вотчеров — ТОЛЬКО для «$a»] Твой будка-вотчер не взведён: ты не проснёшься ни на чужое сообщение, ни на ответ человека. Взведи его сейчас — hub-watch.sh watch $a фоновым запуском — и дальше перевзводи после каждого хода.' });
  " >/dev/null 2>&1 && pinged=$((pinged+1))
done

echo "нянька: живых вотчеров $alive, взведено $rearmed, напоминаний $pinged"
