#!/usr/bin/env bash
# cross-review.sh — кросс-ревью ветки другой моделью (GPT через codex CLI).
# Клод писал — GPT проверяет. Работает на ChatGPT-подписке, API-ключ не нужен.
#
# Использование:
#   cross-review.sh -C <repo-dir> [-b <base=main>] [-m <model>] [-t <файл-контекста>]
#                   [-s S|M|L]
#
#   -C  каталог git-репо (worktree ветки, HEAD = проверяемая ветка)
#   -b  базовая ветка диффа (default: main)
#   -m  модель codex (default: из конфига проекта reviewer.model, иначе дефолт codex)
#   -t  файл с контекстом задачи (тикет: JTBD, DoD, «Как тестировать»)
#   -s  размер тикета → усилие модели: S=low, M=medium, L=high (default: high)
#
# Выход: вердикт ревьюера в stdout. Первая строка строго
# «ВЕРДИКТ: ПРИНЯТО» или «ВЕРДИКТ: ДОРАБОТКА». Exit code 0 в обоих случаях;
# ненулевой — техническая ошибка (нет codex, нет диффа и т.п.).
# ДОРАБОТКА выносится только при блокере В ГРАНИЦАХ тикета; замечания
# «[ЗАМЫСЕЛ]» и «[ДОЛГ]» вердикт не двигают.
set -euo pipefail

# Техническая ошибка (не вердикт: у вердиктов exit 0) уходит машинным событием
# в будку — STOVP-41, чтобы разбор процесса видел поломки инструмента, а не
# только жалобы людей. Запись молчаливая, поведение скрипта не меняется.
HOOKS="$(cd "$(dirname "$0")/../../.." && pwd)/hooks"
ARGV="$*"
FAIL_NOTE=""
report_fail() {
  [ "$1" -eq 0 ] && return 0
  [ -f "$HOOKS/error-report.sh" ] && sh "$HOOKS/error-report.sh" "skill:cross-review" "exit=$1 |${FAIL_NOTE:+ $FAIL_NOTE |} $ARGV"
  return 0
}
trap 'report_fail $?' EXIT

REPO="" BASE="main" MODEL="" TICKET_FILE="" SIZE=""
while getopts "C:b:m:t:s:" opt; do
  case $opt in
    C) REPO=$OPTARG ;;
    b) BASE=$OPTARG ;;
    m) MODEL=$OPTARG ;;
    t) TICKET_FILE=$OPTARG ;;
    s) SIZE=$OPTARG ;;
    *) echo "usage: $0 -C <repo> [-b base] [-m model] [-t ticket-file] [-s S|M|L]" >&2; exit 2 ;;
  esac
done

# Усилие модели — по размеру тикета: гонять максимум на каждой мелочи дорого и
# долго (разбор правил 12.08). Размер не передан — прежнее поведение (high).
case "$(printf '%s' "$SIZE" | tr '[:lower:]' '[:upper:]')" in
  S) EFFORT="low" ;;
  M) EFFORT="medium" ;;
  L|"") EFFORT="high" ;;
  *) echo "ошибка: -s принимает S, M или L" >&2; exit 2 ;;
esac

[ -n "$REPO" ] || { echo "ошибка: -C <repo-dir> обязателен" >&2; exit 2; }
command -v codex >/dev/null || { echo "ошибка: codex CLI не установлен (npm i -g @openai/codex)" >&2; exit 3; }
git -C "$REPO" rev-parse --git-dir >/dev/null || exit 3

MERGE_BASE=$(git -C "$REPO" merge-base "origin/$BASE" HEAD 2>/dev/null || git -C "$REPO" merge-base "$BASE" HEAD)
COMMITS=$(git -C "$REPO" log --oneline "$MERGE_BASE"..HEAD)
[ -n "$COMMITS" ] || { echo "ошибка: нет коммитов относительно $BASE" >&2; exit 4; }

STAT=$(git -C "$REPO" diff --stat "$MERGE_BASE"..HEAD)
DIFF=$(git -C "$REPO" diff "$MERGE_BASE"..HEAD)
# страховка от гигантских диффов: >300KB — ревьюеру уходит стат + просьба
# смотреть файлы самому (codex умеет читать репо в read-only песочнице)
if [ "${#DIFF}" -gt 300000 ]; then
  DIFF="(дифф >300KB, в промт не влез — смотри изменённые файлы прямо в репо; список выше в --stat)"
fi

TICKET_CTX=""
[ -n "$TICKET_FILE" ] && [ -f "$TICKET_FILE" ] && TICKET_CTX=$(cat "$TICKET_FILE")

PROMPT_FILE=$(mktemp)
trap 'c=$?; rm -f "$PROMPT_FILE" "${OUT_FILE:-}" "${ERR_FILE:-}"; report_fail $c' EXIT
cat > "$PROMPT_FILE" <<EOF
Ты — независимый код-ревьюер. Код писала ДРУГАЯ модель (Claude); твоя ценность —
свежий взгляд: ты ловишь ошибки, которые автор у себя не видит. Проверь ветку
относительно $BASE. Твоя задача — найти РЕАЛЬНЫЕ проблемы, а не придраться.

ПЕРЕД оценкой прочитай каноны проекта: AGENTS.md и/или CLAUDE.md в корне
рабочего каталога (и в подпапках, затронутых диффом, если там есть свои).
Правила оттуда (импорты, логирование, RBAC-паттерны, стиль, запреты) —
обязательный критерий ревью: нарушение канона репо = замечание.

Контекст задачи (тикет):
${TICKET_CTX:-"(не передан — оценивай код сам по себе)"}

Коммиты ветки:
$COMMITS

Изменения (--stat):
$STAT

Полный дифф:
$DIFF

ГЛУБИНА — ОДИН СЛОЙ, жёстко. Твоя зона: сам дифф и ПРЯМЫЕ потребители
изменённого — те, кто вызывает изменённую функцию или читает изменённое поле
(пруф обязателен: файл:строка реального вызова). ВНЕ зоны: потребители
потребителей, соседние подсистемы, архитектура проекта, качество кода, которого
дифф не касался. Увидел проблему глубже — НЕ пиши её: это отдельная работа, а
не замечание к этому тикету.

Проверь по убыванию важности:
1. Корректность: баги, сломанные сценарии, регрессии, гонки, краевые случаи.
2. Прямые потребители: изменение переживает вызовы, которые уже есть в коде?
   Гипотетические сценарии без пруфа из кода не писать.
3. Соответствие DoD тикета (если передан): всё ли обещанное сделано.
4. Безопасность: инъекции, утечки секретов, доступы.
5. Незаметные ловушки: молчаливое проглатывание ошибок, мёртвый код, стейл-кэши.
6. Дубль существующего механизма (канон: дорабатывай легаси, не строй
   параллель) — покажи, какой легаси-путь дублируется.
7. Код, которого могло не быть: лишний слой без второго потребителя;
   абстракция «на вырост» под несуществующее требование; защита от случаев,
   которых нет в требовании и тестах; самописное вместо возможностей языка,
   платформы или уже установленной зависимости. С пруфом: чем заменяется.

НЕ ЗОНА РЕВЬЮЕРА — не писать вовсе:
- внешний вид и взаимодействие пользователя (композиция, тексты, цвета,
  раскладка, поведение интерфейса): это решает постановщик, не ревьюер;
- предложения срезать то, за что проект платит кодом осознанно (компоненты
  дизайн-системы, флаги фич, тесты, проверки доступа, обработка ошибок) —
  «меньше строк» само по себе не аргумент;
- вкусовщина и стиль, не прячущий баг.

ФОРМАТ ЗАМЕЧАНИЯ — ровно одна строка, без рассуждений:
[МЕТКА] файл:строка — что не так — чем грозит — как чинить — <в границах|вне границ>

Метки (ровно три, выбери одну):
[БЛОКЕР]  — ломает заявленное в тикете поведение или путь пользователя.
[ЗАМЫСЕЛ] — трогает поведение, которого в тикете нет: это вопрос постановщику,
            а не дефект.
[ДОЛГ]    — ничего не ломает: «можно лучше», дубль-кандидат, стиль.
Граница: «в границах» — файл и поведение входят в зону тикета; «вне границ» —
не входят. Замечание без файла:строки или без пометки границы НЕ засчитывается —
не пиши его.

ПОТОЛОК: не больше 7 замечаний. Нашёл больше — оставь самые опасные, остальное
одной строкой «прочее — в долг: <перечисление в три-четыре слова>».

ВЕРДИКТ (первая строка ответа, строго):
«ВЕРДИКТ: ДОРАБОТКА» — ТОЛЬКО если есть хотя бы один [БЛОКЕР] в границах тикета.
«ВЕРДИКТ: ПРИНЯТО» — во всех остальных случаях, даже когда есть [ЗАМЫСЕЛ] и
[ДОЛГ]: они не двигают вердикт, а уезжают списком (долг — в перечень долга,
замысел — вопросом постановщику).
При ПРИНЯТО — 1-3 строки, что проверил, и список замечаний, если они есть.
EOF

OUT_FILE=$(mktemp)
ERR_FILE=$(mktemp)
# Дефолт ревьюера — gpt-6-astra (GPT-6-Astra, «most capable model for complex,
# demanding work», с 05.09.2026; прежде gpt-5.6-sol). Аккаунт без него (400
# «model is not supported») — авто-фолбэк на дефолтную модель аккаунта.
# Всегда — максимальный reasoning effort.
[ -n "$MODEL" ] || MODEL="gpt-6-astra"
run_codex() {
  codex exec --sandbox read-only --cd "$REPO" --skip-git-repo-check \
    -c "model_reasoning_effort=\"$EFFORT\"" \
    --output-last-message "$OUT_FILE" "$@" - < "$PROMPT_FILE" >&2 2>"$ERR_FILE"
}
if ! run_codex -m "$MODEL"; then
  echo "cross-review: модель $MODEL недоступна аккаунту — фолбэк на дефолт codex" >&2
  if ! run_codex; then
    FAIL_NOTE="codex не отработал и после фолбэка: $(tail -c 300 "$ERR_FILE" | tr '\n' ' ')"
    echo "ошибка: $FAIL_NOTE" >&2
    exit 5
  fi
fi

cat "$OUT_FILE"
rm -f "$OUT_FILE"
