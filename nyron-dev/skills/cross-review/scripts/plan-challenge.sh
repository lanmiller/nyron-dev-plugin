#!/usr/bin/env bash
# plan-challenge.sh — челлендж спеки/плана ДРУГОЙ моделью ДО начала имплементации,
# крест-накрест по автору (engine.sh): план Claude сверяет GPT (codex, Astra), план
# codex — Claude (claude -p, Fable). Пара к Fable-штурму: штурм ищет узкие места
# мышлением, челленджер — сверкой плана с РЕАЛЬНЫМ кодом репо (read-only).
#
# Использование:
#   plan-challenge.sh -C <repo-dir> -t <файл-спеки/плана> [-e codex|claude|auto] [-m <model>] [-M <claude-model>]
#
#   -C  каталог репо главной зоны изменений (worktree/чекаут, read-only)
#   -t  файл: спека/план/раскадровка (JTBD, DoD, нарезка, карта изменений)
#   -e  ревьюер: codex | claude | auto (default auto — по окружению сессии)
#   -m  модель codex (default gpt-6-astra), -M модель claude (default fable);
#       модель недоступна — авто-фолбэк на дефолт аккаунта
#
# Выход: первая строка строго «ПЛАН: ОК» или «ПЛАН: РИСКИ», далее пункты.
set -euo pipefail

# Техническая ошибка (не вердикт: у вердиктов exit 0) уходит машинным событием
# в будку — STOVP-41, чтобы разбор процесса видел поломки инструмента, а не
# только жалобы людей. Запись молчаливая, поведение скрипта не меняется.
HOOKS="$(cd "$(dirname "$0")/../../.." && pwd)/hooks"
ARGV="$*"
FAIL_NOTE=""
report_fail() {
  [ "$1" -eq 0 ] && return 0
  [ -f "$HOOKS/error-report.sh" ] && sh "$HOOKS/error-report.sh" "skill:plan-challenge" "exit=$1 |${FAIL_NOTE:+ $FAIL_NOTE |} $ARGV"
  return 0
}
trap 'report_fail $?' EXIT

REPO="" ENGINE="auto" MODEL="" CLAUDE_MODEL="" PLAN_FILE=""
while getopts "C:t:e:m:M:" opt; do
  case $opt in
    C) REPO=$OPTARG ;;
    t) PLAN_FILE=$OPTARG ;;
    e) ENGINE=$OPTARG ;;
    m) MODEL=$OPTARG ;;
    M) CLAUDE_MODEL=$OPTARG ;;
    *) echo "usage: $0 -C <repo> -t <plan-file> [-e codex|claude|auto] [-m model] [-M claude-model]" >&2; exit 2 ;;
  esac
done
[ -n "$REPO" ] && [ -n "$PLAN_FILE" ] && [ -f "$PLAN_FILE" ] || { echo "ошибка: нужны -C <repo> и -t <файл плана>" >&2; exit 2; }
TAG="plan-challenge"; EFFORT="high"
. "$(dirname "$0")/engine.sh"
engine_resolve

PROMPT_FILE=$(mktemp)
trap 'c=$?; rm -f "$PROMPT_FILE" "${OUT_FILE:-}" "${ERR_FILE:-}"; report_fail $c' EXIT
cat > "$PROMPT_FILE" <<EOF
Ты — независимый архитектурный челленджер ($REVIEWER). План писала ДРУГАЯ модель ($AUTHOR);
твоя ценность — проверить его против РЕАЛЬНОГО кода репо, к которому у тебя
есть доступ на чтение. Имплементация ещё НЕ началась: поймать проблему сейчас
стоит копейки, в мерже — вечер.

ПЕРЕД оценкой прочитай каноны проекта: AGENTS.md и/или CLAUDE.md в корне
рабочего каталога (и в подпапках зоны изменений).

Спека/план на челлендж:
$(cat "$PLAN_FILE")

Проверь по убыванию важности, СВЕРЯЯСЬ С КОДОМ (открывай файлы, названные в
плане, и их соседей):
1. Ложные предпосылки: план ссылается на файлы/функции/поля/эндпоинты, которых
   нет или которые ведут себя иначе, чем план предполагает.
2. Легаси-путь: есть готовый механизм, который план дублирует новым (канон
   проекта: дорабатывай легаси, не строй параллель).
3. Узкие места архитектуры: гонки, состояние между сервисами, миграции данных,
   обратная совместимость, флаги (флоу-правки обязаны быть за env-флагом).
4. Нарезка: куски плана пересекаются по файлам (кандидат на конфликт мержа);
   зависимость между кусками не выписана.
5. Дыры скоупа и СМЕЖНЫЕ УЗЛЫ: краевые случаи из DoD + соседние РЕАЛЬНЫЕ
   режимы/флоу продукта, трогающие те же данные (типовой источник багов:
   спека про создание — а рестарт/переиспользование/edit/publish→use с теми
   же сущностями не отработаны). Сверяйся со списком режимов проекта, если
   передан в контексте, и с реальным кодом; гипотетику без пруфа не писать.
6. Более простой путь: если план можно ужать без потери DoD — покажи как.
Вкусовщину и переименования не писать.

Формат ответа (по-русски, строго):
Первая строка: «ПЛАН: ОК» или «ПЛАН: РИСКИ».
При РИСКАХ — нумерованный список: категория (1-6) — что не так — пруф из кода
(файл:строка/символ) — чем грозит — как поправить план (одной-двумя строками).
При ОК — 2-4 строки: что именно сверил с кодом.
Блок «НЕБЛОКИРУЮЩЕЕ:» — наблюдения, не требующие правки плана.
EOF

OUT_FILE=$(mktemp)
ERR_FILE=$(mktemp)
if ! engine_run; then
  FAIL_NOTE="$ENGINE не отработал и после фолбэка: $(tail -c 300 "$ERR_FILE" | tr '\n' ' ')"
  echo "ошибка: $FAIL_NOTE" >&2
  exit 5
fi
cat "$OUT_FILE"
rm -f "$OUT_FILE"
