/**
 * Набор иконок пульта — офлайн.
 *
 * Пульт живёт на 127.0.0.1 и обязан работать, когда сети нет вообще, поэтому
 * взята офлайн-ветка Iconify (OfflineIcon + addCollection): в ней физически
 * нет кода, ходящего в api.iconify.design. Обычный `@iconify/svelte` за
 * незнакомой иконкой лезет в интернет и без него рисует пустоту — здесь такое
 * невозможно, набор целиком лежит в node_modules и попадает в сборку.
 *
 * Набор кладётся целиком (~570 КБ JSON) сознательно: страница читается с
 * локального диска, а вырезать подмножество — это сборочный плагин плюс
 * список имён, который придётся вести руками и который будет отставать.
 * Если бандл когда-нибудь начнёт мешать, менять надо только этот файл:
 * вызовы <Icon name="…"> его не видят.
 */
import { addCollection } from '@iconify/svelte/dist/offline-functions';
import lucide from '@iconify-json/lucide/icons.json';

addCollection(lucide);

/** Префикс набора: с ним имя иконки уходит в хранилище Iconify. */
export const ICON_PREFIX = `${lucide.prefix}:`;
