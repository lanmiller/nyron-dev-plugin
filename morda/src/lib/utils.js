import { clsx } from 'clsx';
import { twMerge } from 'tailwind-merge';

/**
 * Склейка классов для компонентов shadcn (они зовут её по имени `cn`).
 *
 * Зачем не просто шаблонная строка: у Tailwind побеждает не последний класс в
 * строке, а тот, что стоит позже в собранном CSS, — поэтому `p-2 p-4` даёт
 * непредсказуемый отступ. twMerge выкидывает конфликтующие пары, оставляя
 * последнюю, и переданный сверху класс действительно перебивает базовый.
 */
export function cn(...inputs) {
  return twMerge(clsx(inputs));
}
